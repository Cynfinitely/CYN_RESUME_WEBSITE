import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";
import { findAiAttribution } from "./check-ai-attribution.mjs";

const script = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "check-ai-attribution.mjs"
);

test("clean message passes", () => {
  assert.deepEqual(
    findAiAttribution("feat(api): add wizard step\n\nBody text.\n"),
    []
  );
});

test("human co-author passes", () => {
  assert.deepEqual(
    findAiAttribution(
      "fix: x\n\nCo-authored-by: Jane Doe <jane@example.com>\nSigned-off-by: Jane Doe <jane@example.com>\n"
    ),
    []
  );
});

for (const trailer of [
  "Co-authored-by: Cursor <cursoragent@cursor.com>",
  "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
  "Co-authored-by: Copilot <198982749+Copilot@users.noreply.github.com>",
  "co-authored-by: Codex <codex@openai.com>",
  "Assisted-by: Gemini",
  "Signed-off-by: Devin AI <devin-ai-integration[bot]@users.noreply.github.com>",
]) {
  test(`rejects trailer: ${trailer}`, () => {
    assert.deepEqual(findAiAttribution(`feat: x\n\n${trailer}\n`), [trailer]);
  });
}

for (const footer of [
  "🤖 Generated with [Claude Code](https://claude.com/claude-code)",
  "Generated with Claude Code",
  "Made with Cursor",
  "Generated by Copilot",
]) {
  test(`rejects footer: ${footer}`, () => {
    assert.deepEqual(findAiAttribution(`Summary\n\n${footer}\n`), [footer]);
  });
}

test("handles CRLF line endings", () => {
  assert.deepEqual(
    findAiAttribution(
      "feat: x\r\n\r\nCo-authored-by: Cursor <cursoragent@cursor.com>\r\n"
    ),
    ["Co-authored-by: Cursor <cursoragent@cursor.com>"]
  );
});

test("mentioning a tool in prose passes", () => {
  assert.deepEqual(
    findAiAttribution("docs: explain the Cursor commit attribution setting\n"),
    []
  );
});

test("skips git comment lines and the verbose diff", () => {
  const message = [
    "feat: x",
    "# Co-authored-by: Cursor <cursoragent@cursor.com>",
    "# ------------------------ >8 ------------------------",
    "+Co-authored-by: Cursor <cursoragent@cursor.com>",
  ].join("\n");
  assert.deepEqual(findAiAttribution(message, { skipGitComments: true }), []);
});

test("CLI exits 1 on a commit message file with an AI trailer", () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "ai-attribution-"));
  const file = path.join(dir, "COMMIT_EDITMSG");
  fs.writeFileSync(
    file,
    "feat: x\n\nCo-authored-by: Cursor <cursoragent@cursor.com>\n"
  );
  const result = spawnSync(process.execPath, [script, file], {
    encoding: "utf8",
  });
  assert.equal(result.status, 1);
  assert.match(result.stderr, /no-ai-attribution\.md/);
});

test("CLI exits 0 on a clean stdin body", () => {
  const result = spawnSync(
    process.execPath,
    [script, "--stdin", "--label", "PR body"],
    { encoding: "utf8", input: "## Summary\n\nRefactor tokens.\n" }
  );
  assert.equal(result.status, 0);
});
